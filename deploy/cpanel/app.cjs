const path = require("node:path");

const appRoot = path.resolve(__dirname, "../..");
const standaloneRoot = path.join(appRoot, ".next", "standalone");

function validateConfiguration() {
  const [major, minor] = process.versions.node.split(".").map(Number);
  if (major < 22 || (major === 22 && minor < 16)) {
    throw new Error("A Agenda Realess requer Node.js 22.16 ou superior para usar o SQLite integrado.");
  }

  if (!process.env.PUBLIC_URL) {
    throw new Error("Configure PUBLIC_URL no cPanel, por exemplo https://agenda.realess.com.br.");
  }
  const publicUrl = new URL(process.env.PUBLIC_URL);
  if (publicUrl.protocol !== "https:" || publicUrl.username || publicUrl.password || publicUrl.pathname !== "/" || publicUrl.search || publicUrl.hash) {
    throw new Error("PUBLIC_URL deve ser a origem HTTPS da agenda, sem caminho adicional.");
  }

  if (!process.env.AGENDA_DB_PATH || !path.isAbsolute(process.env.AGENDA_DB_PATH)) {
    throw new Error("Configure AGENDA_DB_PATH como caminho absoluto e gravável fora de public_html.");
  }

  process.env.TZ ||= "America/Sao_Paulo";
  process.env.NEXT_TELEMETRY_DISABLED = "1";
  process.env.AGENDA_MIGRATIONS_DIR = path.join(standaloneRoot, "drizzle");
}

async function start() {
  // Keep records beside the checked-out app, outside public_html. Git ignores
  // SQLite files, so deployments preserve data generated by managers' tests.
  process.env.AGENDA_DB_PATH = path.join(appRoot, "banco-de-dados", "agenda.sqlite");
  process.env.AGENDA_BACKUP_DIR = path.join(appRoot, "banco-de-dados", "backups");
  validateConfiguration();
  process.chdir(standaloneRoot);

  // Create the persistent database and apply migrations before Passenger accepts requests.
  const { getDatabase } = await import(path.join(standaloneRoot, "db", "local-sqlite.mjs"));
  getDatabase();

  // Next standalone reads Passenger's PORT and starts its HTTP server.
  await import(path.join(standaloneRoot, "server.js"));
}

start().catch((error) => {
  console.error("Falha ao iniciar a Agenda Realess no cPanel:", error);
  process.exitCode = 1;
});
